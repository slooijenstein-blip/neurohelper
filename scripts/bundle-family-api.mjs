import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "scripts/family-api-entry.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: path.join(root, "api/family-handler.js"),
  banner: {
    js: "// Generated by scripts/bundle-family-api.mjs. Do not edit.",
  },
  logLevel: "info",
});
